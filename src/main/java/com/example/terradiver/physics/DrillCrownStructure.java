    public static int[][] cells(String size) {
        return switch (size) {
            case "1x1" -> CELLS_1x1;
            case "3x3" -> CELLS_3x3;
            case "5x5" -> CELLS_5x5;
            case "7x7" -> CELLS_7x7;
            case "9x9" -> CELLS_9x9;
            case "11x11" -> CELLS_11x11;
            default -> throw new IllegalArgumentException("unknown crown size: " + size);
        };
    }

    /*
     * Повернуть смещение ячейки (модельное пространство, ось глубины +Y) в мировое по FACING.
     * UP — без изменений; остальные грани отображают +Y на нужное направление, сохраняя сечение.
     */
    public static int[] rotate(int[] off, Direction facing) {
        int x = off[0], y = off[1], z = off[2];
        return switch (facing) {
            case UP    -> new int[]{ x,  y,  z};
            case DOWN  -> new int[]{ x, -y, -z};
            case NORTH -> new int[]{ x,  z, -y};
            case SOUTH -> new int[]{ x, -z,  y};
            case EAST  -> new int[]{ y, -x,  z};
            case WEST  -> new int[]{-y,  x,  z};
        };
    }

    /*
     * Мировые позиции всех ячеек структуры: мастер + повёрнутые по FACING смещения.
     * Первая в списке — позиция мастера (смещение 0,0,0).
     */
    public static List<BlockPos> worldCells(String size, Direction facing, BlockPos master) {
        List<BlockPos> out = new ArrayList<>();
        for (int[] off : cells(size)) {
            int[] r = rotate(off, facing);
            out.add(master.offset(r[0], r[1], r[2]));
        }
        return out;
    }
